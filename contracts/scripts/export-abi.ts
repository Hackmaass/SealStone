import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(__dirname, "../..");
const ARTIFACTS = path.resolve(__dirname, "../artifacts/contracts");
const OUT = path.join(ROOT, "web", "src", "generated", "contracts.ts");

const CONTRACTS: Array<[name: string, file: string]> = [
  ["MilestoneVault", "MilestoneVault.sol/MilestoneVault.json"],
  ["ReentrantProvider", "attack/ReentrantProvider.sol/ReentrantProvider.json"],
  ["RejectingProvider", "attack/RejectingProvider.sol/RejectingProvider.json"],
  ["NaiveEscrow", "attack/NaiveEscrow.sol/NaiveEscrow.json"],
  ["NaiveDrainer", "attack/NaiveDrainer.sol/NaiveDrainer.json"],
  ["ForceSender", "attack/ForceSender.sol/ForceSender.json"],
];

function main(): void {
  const parts = CONTRACTS.map(([name, file]) => {
    const art = JSON.parse(readFileSync(path.join(ARTIFACTS, file), "utf8"));
    return `export const ${name} = ${JSON.stringify({ abi: art.abi, bytecode: art.bytecode })};\n`;
  });
  mkdirSync(path.dirname(OUT), { recursive: true });
  writeFileSync(OUT, `// GENERATED by contracts/scripts/export-abi.ts. Do not edit.\n/* eslint-disable */\n${parts.join("\n")}`);
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${CONTRACTS.map(([n]) => n).join(", ")})`);
}

main();
